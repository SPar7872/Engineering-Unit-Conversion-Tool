public class MassConverter {

    public double kilogramsToPounds(double kg) {
        return kg * 2.20462;
    }

    public double poundsToKilograms(double lb) {
        return lb / 2.20462;
    }

    public double gramsToOunces(double g) {
        return g * 0.035274;
    }

    public double ouncesToGrams(double oz) {
        return oz / 0.035274;
    }
}
